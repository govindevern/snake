"""Build and smoke-test the standalone Windows x64 Snake release."""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import os
import platform
import shutil
import subprocess
import sys
import tempfile
import zipfile
import uuid
from pathlib import Path

from snake_lang import __version__


ROOT = Path(__file__).resolve().parent
BUILD_ROOT = ROOT / "build" / f"v{__version__}-{uuid.uuid4().hex[:8]}"
RELEASE_ROOT = ROOT / "release" / f"v{__version__}"
MARKER = ".snake-generated-release"


def run_checked(command: list[str], **kwargs: object) -> subprocess.CompletedProcess[str]:
    print("+", subprocess.list2cmdline(command), flush=True)
    return subprocess.run(command, check=True, text=True, **kwargs)


def _prepare_owned_directory(path: Path, marker: str,
                             marker_path: Path | None = None) -> None:
    ownership_marker = marker_path or path / marker
    if path.exists():
        if not ownership_marker.is_file():
            raise RuntimeError(
                f"Refusing to replace unmarked directory: {path}. "
                "Move its contents or remove it yourself before building."
            )
        shutil.rmtree(path)
    path.mkdir(parents=True)
    ownership_marker.parent.mkdir(parents=True, exist_ok=True)
    ownership_marker.write_text("Generated by build.py.\n", encoding="utf-8")


def _build_format(format_name: str) -> Path:
    output_dir = BUILD_ROOT / f"dist-{format_name}"
    work_dir = BUILD_ROOT / f"work-{format_name}"
    output_dir.mkdir(parents=True, exist_ok=True)
    work_dir.mkdir(parents=True, exist_ok=True)
    command = [
        sys.executable, "-m", "PyInstaller", "--noconfirm", "--clean",
        "--console", "--name", "snake",
        "--distpath", str(output_dir), "--workpath", str(work_dir),
        "--specpath", str(BUILD_ROOT),
        "--paths", str(ROOT),
    ]
    if format_name == "onefile":
        command.append("--onefile")
    else:
        command.append("--onedir")
    command.append(str(ROOT / "snake.py"))
    run_checked(command, cwd=ROOT)
    executable = output_dir / "snake.exe"
    if format_name == "onedir":
        executable = output_dir / "snake" / "snake.exe"
    if not executable.is_file():
        raise RuntimeError(f"PyInstaller did not produce {executable}")
    return executable


def _isolated_environment() -> dict[str, str]:
    environment = os.environ.copy()
    for key in list(environment):
        if key.upper().startswith("PYTHON"):
            del environment[key]
    environment["PATH"] = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32")
    return environment


def _invoke(executable: Path, args: list[str], cwd: Path, environment: dict[str, str],
            input_text: str | None = None) -> subprocess.CompletedProcess[str]:
    result = subprocess.run(
        [str(executable), *args],
        cwd=cwd,
        env=environment,
        input=input_text,
        capture_output=True,
        text=True,
        timeout=90,
        check=False,
    )
    print(f"[{executable.name} {' '.join(args)}] exit={result.returncode}")
    if result.stdout:
        print(result.stdout.rstrip())
    if result.stderr:
        print(result.stderr.rstrip(), file=sys.stderr)
    return result


def verify_executable(executable: Path) -> bool:
    executable = executable.resolve()
    environment = _isolated_environment()
    with tempfile.TemporaryDirectory(prefix="snake-standalone-") as temporary:
        work = Path(temporary)
        program = work / "hello.snake"
        program.write_text(
            'let value = 81\n'
            'show "Hello from standalone Snake"\n'
            'show math.sqrt(value)\n'
            'show system.version\n'
            'files.write("created.txt", "resource access works")\n'
            'show files.read("created.txt")\n',
            encoding="utf-8",
        )
        invalid = work / "invalid.snake"
        invalid.write_text("show )\n", encoding="utf-8")
        runtime_error = work / "runtime-error.snake"
        runtime_error.write_text("show 1 / 0\n", encoding="utf-8")

        version = _invoke(executable, ["--version"], work, environment)
        help_result = _invoke(executable, ["--help"], work, environment)
        relative_run = _invoke(executable, ["run", "hello.snake"], work, environment)
        absolute_check = _invoke(executable, ["check", str(program)], work, environment)
        invalid_check = _invoke(executable, ["check", str(invalid)], work, environment)
        runtime_failure = _invoke(executable, ["run", str(runtime_error)], work, environment)
        repl = _invoke(executable, ["repl"], work, environment, "show 2 + 3\n:quit\n")
        output_file = work / "created.txt"
        expected = (
            version.returncode == 0 and f"Snake {__version__}" in version.stdout
            and help_result.returncode == 0 and "usage:" in help_result.stdout.lower()
            and relative_run.returncode == 0
            and "Hello from standalone Snake" in relative_run.stdout
            and "9" in relative_run.stdout and __version__ in relative_run.stdout
            and "resource access works" in relative_run.stdout
            and output_file.is_file()
            and absolute_check.returncode == 0 and "OK:" in absolute_check.stdout
            and invalid_check.returncode == 1 and "invalid.snake" in invalid_check.stderr
            and runtime_failure.returncode == 1 and "Division by zero" in runtime_failure.stderr
            and repl.returncode == 0 and "Snake " in repl.stdout and "5" in repl.stdout
        )
    if not expected:
        print(f"Standalone verification failed for {executable}", file=sys.stderr)
    else:
        print(f"Standalone verification passed without Python on PATH: {executable}")
    return expected


def _stage_distribution(executable: Path, format_name: str) -> None:
    destination = RELEASE_ROOT / "standalone"
    if format_name == "onedir":
        source_directory = executable.parent
        shutil.copytree(source_directory, destination, dirs_exist_ok=True)
    else:
        destination.mkdir(exist_ok=True)
        shutil.copy2(executable, destination / "snake.exe")


def _write_release_files(format_name: str) -> None:
    for name in ("README.md", "LICENSE", "RELEASE_NOTES.md"):
        shutil.copy2(ROOT / name, RELEASE_ROOT / name)
    build_info = (
        f"Snake: {__version__}\n"
        f"Target: Windows x64\n"
        f"Python build runtime: {platform.python_version()}\n"
        f"PyInstaller: {importlib.metadata.version('pyinstaller')}\n"
        f"Bundle format: {format_name}\n"
    )
    (RELEASE_ROOT / "BUILD_INFO.txt").write_text(build_info, encoding="utf-8")
    archive = RELEASE_ROOT / f"Snake-Standalone-{__version__}.zip"
    with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as bundle:
        for name in ("README.md", "LICENSE", "RELEASE_NOTES.md", "BUILD_INFO.txt"):
            bundle.write(RELEASE_ROOT / name, name)
        for path in sorted((RELEASE_ROOT / "standalone").rglob("*")):
            if path.is_file():
                bundle.write(path, path.relative_to(RELEASE_ROOT))


def _write_checksums() -> None:
    lines: list[str] = []
    for path in sorted(RELEASE_ROOT.rglob("*")):
        if not path.is_file() or path.name in (MARKER, "SHA256SUMS.txt"):
            continue
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f"{digest}  {path.relative_to(RELEASE_ROOT).as_posix()}")
    (RELEASE_ROOT / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n", encoding="ascii")


def _find_iscc() -> Path | None:
    configured = os.environ.get("INNO_SETUP_COMPILER")
    candidates = [
        Path(configured) if configured else None,
        Path(shutil.which("ISCC.exe")) if shutil.which("ISCC.exe") else None,
        Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / "Inno Setup 6" / "ISCC.exe",
        Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "Inno Setup 6" / "ISCC.exe",
        Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Inno Setup 6" / "ISCC.exe",
    ]
    return next((path for path in candidates if path is not None and path.is_file()), None)


def build_installer() -> None:
    compiler = _find_iscc()
    if compiler is None:
        raise RuntimeError(
            "Inno Setup 6 ISCC.exe was not found. Install Inno Setup 6, then rerun "
            "this command, or use --exe-only to build just the verified standalone release."
        )
    run_checked([str(compiler), str(ROOT / "installer" / "snake.iss")], cwd=ROOT)
    installer = RELEASE_ROOT / f"Snake-Setup-{__version__}.exe"
    if not installer.is_file():
        raise RuntimeError(f"Inno Setup did not produce {installer}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--format", choices=("onefile", "onedir", "both"), default="both",
                        help="build format(s); both evaluates single-file against onedir")
    parser.add_argument("--exe-only", action="store_true",
                        help="skip installer compilation even when Inno Setup is available")
    args = parser.parse_args()
    if (sys.platform != "win32" or platform.machine().lower() not in ("amd64", "x86_64")
            or platform.architecture()[0] != "64bit" or sys.maxsize <= 2**32):
        parser.error("the release executable must be built on Windows x64.")
    run_checked(
        [sys.executable, "-m", "unittest", "discover", "-s", "tests", "-v"],
        cwd=ROOT,
    )
    _prepare_owned_directory(BUILD_ROOT, MARKER)
    release_marker = RELEASE_ROOT.parent / f".snake-generated-v{__version__}"
    if RELEASE_ROOT.exists() and not release_marker.is_file():
        raise RuntimeError(
            f"Refusing to write into an unmarked release directory: {RELEASE_ROOT}"
        )
    RELEASE_ROOT.mkdir(parents=True, exist_ok=True)
    release_marker.parent.mkdir(parents=True, exist_ok=True)
    release_marker.write_text("Generated by build.py.\n", encoding="utf-8")

    formats = ("onefile", "onedir") if args.format == "both" else (args.format,)
    results = {name: _build_format(name) for name in formats}
    passed = {name: verify_executable(path) for name, path in results.items()}
    if not any(passed.values()):
        raise RuntimeError("No standalone format passed the smoke tests.")
    selected = "onefile" if passed.get("onefile", False) else "onedir"
    if selected not in results:
        selected = next(name for name in formats if passed[name])
    print(f"Selected release format: {selected}")
    _stage_distribution(results[selected], selected)
    _write_release_files(selected)
    if not args.exe_only:
        build_installer()
    _write_checksums()
    print(f"Release files: {RELEASE_ROOT}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"Build failed: {error}", file=sys.stderr)
        raise SystemExit(1) from error
